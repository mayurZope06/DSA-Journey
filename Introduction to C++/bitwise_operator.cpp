#include <iostream>
using namespace std;
int main()
{
    // & AND
    cout<< (5&4) <<endl;

    // | OR
    cout<<(5|4)<<endl;

    // ~ NOT
    cout<<(~5)<<endl;

    // << Left Shift
    cout<<(5<<2)<<endl;
    cout<<(5<<1)<<endl;

    // >> Right Shift
    cout<<(1>>1)<<endl;
    cout<<(100>>2)<<endl;

    // ^ XOR
    cout<<(5^5)<<endl;
    cout<<(5^4)<<endl;
    
    return 0;
}